#!/usr/bin/env bash
# Regenerates ui/src/api/generated/*.ts from the Rust wire types (ts-rs).
# See docs/content/contributing/typescript-bindings.mdx.
set -euo pipefail
cd "$(dirname "$0")/.."

out=ui/src/api/generated

# Export into a scratch directory and swap it in at the end. CL_API_SKIP_UI_BUILD
# keeps cl-api's build script from typechecking the ui, which imports files
# this script has not written yet.
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# 64-bit integers are plain JSON numbers on the wire (and in the ui), not bigint.
CL_API_SKIP_UI_BUILD=1 TS_RS_EXPORT_DIR="$tmp" TS_RS_LARGE_INT=number \
  cargo test \
    -p cl-alert -p cl-api -p cl-backup -p cl-config -p cl-raft -p cl-restic -p cl-sched \
    --features ts export_bindings_

# A barrel so the ui can import any generated type from one place.
{
  echo "// Generated by scripts/gen-ts-bindings.sh. Do not edit."
  for f in $(cd "$tmp" && LC_ALL=C ls *.ts); do
    n="${f%.ts}"
    echo "export type { $n } from './$n';"
  done
} > "$tmp.index"
mv "$tmp.index" "$tmp/index.ts"

rm -rf "$out"
mkdir -p "$out"
cp "$tmp"/*.ts "$out"/
